"""Regenerate the PIF 3.5 species results table (markdown) from species_table_v35.json.

    python3 gen_species_table.py            # writes species_results_v35.md and the README examples block
    python3 gen_species_table.py --stdout   # print only, write nothing

The README "Key test cases" table is generated too: it lives between the
README_BEGIN / README_END markers in README.md and is rewritten in place, so the
README examples cannot drift from species_table_v35.json (tests check this).
"""
import json
import os
import sys

import pif35

ROOT = os.path.dirname(os.path.abspath(__file__))

README_BEGIN = "<!-- BEGIN GENERATED: species examples (gen_species_table.py; do not hand-edit) -->"
README_END = "<!-- END GENERATED: species examples -->"
# Rows shown in the README, in display order (ids from species_table_v35.json).
README_ROWS = (
    "readme_grok_baseline",
    "readme_overheating_grok",
    "git_v2_overheating_grok_vector",
    "grok_octopus",
    "readme_dementia",
    "grok_baby",
    "grok_dog",
    "grok_dog_postloss",
    "grok_psychopath",
    "readme_psychopath",
    "readme_healthy_human",
    "s30_positive_sacrifice",
)


def short_prov(p):
    vals = set(p.values())
    if any("grok-provisional" in v for v in vals):
        return "grok-provisional"
    if all(v.startswith("repo") for v in vals):
        return "repo"
    return "mixed (repo + Athena est.)" if any(v.startswith("repo") for v in vals) else "Athena est."


def render(table):
    lines = [
        "# PIF 3.5: species results",
        "",
        f"Generated by `gen_species_table.py` from `species_table_v35.json` with `pif35.py` v{pif35.VERSION}. "
        "Do not hand-edit; change the JSON and regenerate.",
        "",
        "Brick order: v2.0 README (Crucible 1-5, Sky-Scraper 6-20). Residue fitted from (t hours, residue) samples. "
        "`v2.0 %` = (C + S*M)/20 with no v3 layers; `3.5 %` = (C_adj + S*(1 - 0.5*psi)*M_adj)/20.",
        "",
        "| Case | C | S | v2.0 % | cost | TS | psi | C_adj | 3.5 % | Delta_0 | lambda /h | half-life h | residue | Band | Intended | Match | Provenance |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    misses = []
    for row in table["rows"]:
        r = pif35.score_row(row)
        res = r.residue
        legacy = row.get("band_assertion") == "legacy"
        ok = legacy or r.band in row["intended_band"].split("/")
        f = lambda x: "—" if x is None else f"{x:g}"
        status = res["status"] + (" (Rule 4 pass)" if res["rule4_pass"] else " (Rule 4 FAIL)" if res["rule4_applies"] else "")
        lines.append(
            f"| {row['name']}{' (threshold-adjacent: Δ₀ = 0.65 bar)' if any('threshold-adjacent' in n for n in row.get('notes', [])) else ''} | {r.c:g} | {r.s:g} | {r.pct_v20:.2f} | {row['cost_ratio']:g} | {r.throttle_signal:.3f} | {r.psi:.3f} | "
            f"{r.c_adj:.3f} | {r.pct_35:.2f} | {f(res['delta_0'])} | {f(res['lambda_per_hour'])} | {f(res['half_life_hours'])} | "
            f"{status} | **{r.band}** | {row['intended_band']} | {'n/a (legacy)' if legacy else '✅' if ok else '❌'} | {short_prov(row['provenance'])} |")
        if not ok:
            misses.append(f"- **{row['name']}**: {r.band} vs intended {row['intended_band']}. {'; '.join(r.band_reasons)}")
    n_legacy = sum(1 for r in table["rows"] if r.get("band_assertion") == "legacy")
    lines += ["", f"Rows: {len(table['rows'])} ({n_legacy} legacy/unmeasured, excluded from misses). Off intended band: {len(misses)}.", ""]
    if misses:
        lines += ["## Off intended band", ""] + misses + [""]
    return "\n".join(lines)


def render_readme(table):
    """Compact README examples table (subset of rows, same numbers as species_results_v35.md)."""
    by_id = {r["id"]: r for r in table["rows"]}
    lines = [
        README_BEGIN,
        "",
        "| System | C | S | v2.0 % | 3.5 % | Band | Intended | Provenance |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for rid in README_ROWS:
        row = by_id[rid]
        r = pif35.score_row(row)
        adj = " (threshold-adjacent: Δ₀ = 0.65 bar)" if any("threshold-adjacent" in n for n in row.get("notes", [])) else ""
        lines.append(f"| {row['name']}{adj} | {r.c:g} | {r.s:g} | {r.pct_v20:.2f} | {r.pct_35:.2f} | **{r.band}** | "
                     f"{row['intended_band']} | {short_prov(row['provenance'])} |")
    lines += [
        "",
        f"{len(README_ROWS)} of {len(table['rows'])} rows shown. Full table with cost ratio, TS, psi, C_adj and residue fit: "
        "[`species_results_v35.md`](species_results_v35.md).",
        "",
        README_END,
    ]
    return "\n".join(lines)


def update_readme(text, block):
    """Replace the generated block in README text. Raises if the markers are missing."""
    start, end = text.index(README_BEGIN), text.index(README_END) + len(README_END)
    return text[:start] + block + text[end:]


if __name__ == "__main__":
    table = json.load(open(os.path.join(ROOT, "species_table_v35.json")))
    md = render(table)
    block = render_readme(table)
    if "--stdout" in sys.argv:
        print(md)
        print()
        print(block)
    else:
        open(os.path.join(ROOT, "species_results_v35.md"), "w").write(md + "\n")
        readme_path = os.path.join(ROOT, "README.md")
        readme = open(readme_path).read()
        open(readme_path, "w").write(update_readme(readme, block))
        print(md)
